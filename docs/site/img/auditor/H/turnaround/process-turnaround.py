#!/usr/bin/env python3
"""Key retained image_gen renders; align, encode and inspect the Hover views.

Run from the repository root with .venv/bin/python. Artwork is generated by
image_gen; this script only keys/despills, resizes, translates and lays out QA.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import runpy

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
HOVER = ROOT.parent
HELPERS = runpy.run_path(str(HOVER.parent / "process-auditor.py"))
CANVAS = (512, 512)
SCALE = 0.53
NOZZLE = (256, 494)
LIMIT = 80_000
VIEWS = {
    "front": {"yaw": 0, "anchor": (624, 1011)},
    "three-quarter-left": {"yaw": 45, "anchor": (618, 1004)},
    "side-left": {"yaw": 90, "anchor": (622.5, 1010)},
    "three-quarter-back": {"yaw": 135, "anchor": (614.5, 1001)},
    "back": {"yaw": 180, "anchor": (617, 1010)},
}
REFERENCES = ("idle.webp", "point.webp", "stamp.webp", "contact.png")


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def font(size: int):
    return ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial.ttf", size)


def alpha_metrics(image: Image.Image) -> dict:
    a = np.asarray(image).astype(np.int16)
    alpha = a[..., 3]
    pink = (np.minimum(a[..., 0], a[..., 2]) - a[..., 1] > 35) & (alpha > 32)
    return {
        "alpha_min": int(alpha.min()), "alpha_max": int(alpha.max()),
        "alpha_levels": int(np.unique(alpha).size),
        "transparent_pixels": int(np.count_nonzero(alpha == 0)),
        "partial_alpha_pixels": int(np.count_nonzero((alpha > 0) & (alpha < 255))),
        "magenta_spill_pixels_alpha_gt_32": int(np.count_nonzero(pink)),
        "border_coverage_pixels": int(np.count_nonzero(alpha[0]))
        + int(np.count_nonzero(alpha[-1])) + int(np.count_nonzero(alpha[:, 0]))
        + int(np.count_nonzero(alpha[:, -1])),
        "exhaust_corridor_pixels": int(np.count_nonzero(alpha[498:, 240:273])),
    }


def build_exports() -> dict:
    records = {}
    for name, view in VIEWS.items():
        source = ROOT / "source" / f"{name}.png"
        original = Image.open(source)
        assert original.size == (1254, 1254), (name, original.size)
        keyed, background = HELPERS["key_and_despill"](original)
        scaled = keyed.resize(tuple(round(n * SCALE) for n in keyed.size), Image.Resampling.LANCZOS)
        offset = tuple(NOZZLE[i] - round(view["anchor"][i] * SCALE) for i in (0, 1))
        final = Image.new("RGBA", CANVAS)
        final.paste(scaled, offset)
        final = HELPERS["final_despill"](final)
        pre_bbox = final.getbbox()
        source_bbox = scaled.getbbox()
        assert source_bbox[0] + offset[0] > 0 and source_bbox[1] + offset[1] > 0
        assert source_bbox[2] + offset[0] < 512 and source_bbox[3] + offset[1] < 512
        path = ROOT / f"{name}.webp"
        final.save(path, "WEBP", quality=90, method=6, alpha_quality=100, exact=True)
        decoded = Image.open(path).convert("RGBA")
        metrics = alpha_metrics(decoded)
        assert path.stat().st_size <= LIMIT, (name, path.stat().st_size)
        assert metrics["alpha_min"] == 0 and metrics["alpha_max"] == 255
        assert metrics["partial_alpha_pixels"] > 0
        assert metrics["magenta_spill_pixels_alpha_gt_32"] == 0, (name, metrics)
        assert metrics["border_coverage_pixels"] == 0, (name, metrics)
        assert metrics["exhaust_corridor_pixels"] == 0, (name, metrics)
        assert decoded.getbbox() == pre_bbox
        bbox = decoded.getbbox()
        records[name] = {
            "file": path.name, "bytes": path.stat().st_size, "sha256": digest(path),
            "size": list(decoded.size), "alpha_bbox": list(bbox),
            "alpha_content_height": bbox[3] - bbox[1], "yaw_degrees_toward_screen_left": view["yaw"],
            "source": f"source/{source.name}", "source_sha256": digest(source),
            "source_size": list(original.size), "source_nozzle_anchor": list(view["anchor"]),
            "measured_background_rgb": background, "scale": SCALE,
            "translation": list(offset), "nozzle_anchor": list(NOZZLE),
            "encoding": {"format": "WEBP", "quality": 90, "method": 6, "alpha_quality": 100, "exact": True},
            "qa": metrics,
        }
    return records


def build_sheet() -> None:
    sheet = Image.new("RGB", (2560, 1200))
    draw = ImageDraw.Draw(sheet)
    for top, bg, ink, label in [(0, "#111a20", "#f7f5ef", "DARK"), (600, "#f7f5ef", "#111a20", "LIGHT")]:
        draw.rectangle((0, top, 2559, top + 599), fill=bg)
        draw.text((24, top + 15), f"HOVER / TURNAROUND / {label} / NO FLAME", font=font(25), fill=ink)
        for index, (name, view) in enumerate(VIEWS.items()):
            sprite = Image.open(ROOT / f"{name}.webp").convert("RGBA")
            panel = Image.new("RGBA", CANVAS, bg)
            panel.alpha_composite(sprite)
            sheet.paste(panel.convert("RGB"), (index * 512, top + 52))
            text = f"{view['yaw']}° / {name.replace('-', ' ')}"
            center = index * 512 + 256
            draw.text((center, top + 576), text, font=font(18), fill=ink, anchor="mm")
    sheet.save(ROOT / "sheet.png", optimize=True)


def build_edge_sheet() -> None:
    """Show decoded nozzle, stamp and antenna contours at 3x on both themes."""
    stamp_centers = {
        "front": (73, 470), "three-quarter-left": (91, 463),
        "side-left": (166, 457), "three-quarter-back": (407, 449),
        "back": (436, 469),
    }
    sheet = Image.new("RGB", (1500, 1560))
    draw = ImageDraw.Draw(sheet)
    for top, bg, ink, label in [(0, "#111a20", "#f7f5ef", "DARK"), (780, "#f7f5ef", "#111a20", "LIGHT")]:
        draw.rectangle((0, top, 1499, top + 779), fill=bg)
        draw.text((14, top + 8), f"DECODED WEBP / 3x EDGE INSPECTION / {label}", font=font(19), fill=ink)
        for index, name in enumerate(VIEWS):
            sprite = Image.open(ROOT / f"{name}.webp").convert("RGBA")
            a = np.asarray(sprite)
            yy, xx = np.indices(a.shape[:2])
            ball = (a[..., 3] > 230) & (a[..., 1] > 170) & (a[..., 0] < 150) & (yy < 100)
            by, bx = np.nonzero(ball)
            ball_center = (round(float(bx.mean())), round(float(by.mean())))
            centers = [(256, 474), stamp_centers[name], ball_center]
            crops = [(x - 50, y - 40, x + 50, y + 40) for x, y in centers]
            draw.text((index * 300 + 8, top + 40), name, font=font(15), fill=ink)
            for row, crop in enumerate(crops):
                tile = Image.new("RGBA", (100, 80), bg)
                tile.alpha_composite(sprite.crop(crop))
                tile = tile.resize((300, 240), Image.Resampling.NEAREST)
                sheet.paste(tile.convert("RGB"), (index * 300, top + 60 + row * 240))
    sheet.save(ROOT / "edge-check.png", optimize=True)


def main() -> None:
    views = build_exports()
    build_sheet()
    build_edge_sheet()
    sources = {str(p.relative_to(ROOT)): {"bytes": p.stat().st_size, "sha256": digest(p)}
               for p in sorted((ROOT / "source").glob("*.png"))}
    manifest = {
        "created": "2026-11-02", "tool": "built-in image_gen",
        "reference_sha256": {name: digest(HOVER / name) for name in REFERENCES},
        "shared_scale": SCALE, "canvas": list(CANVAS), "nozzle_anchor": list(NOZZLE),
        "stamp_hand": "anatomical right, following approved idle.webp and point.webp",
        "backdrop_request": "opaque flat #FF00FF; measured near-magenta keyed per source",
        "processing": "existing key_and_despill and final_despill; one shared resize; per-view translation; no redrawing",
        "sources": sources, "views": views,
        "review_assets": {name: {"bytes": (ROOT / name).stat().st_size, "sha256": digest(ROOT / name)}
                          for name in ("sheet.png", "edge-check.png")},
        "limitations": [
            "Generated rotations, not renders of one reconstructed 3D model; exact multi-view identity cannot be guaranteed.",
            "Antenna bend radius and lateral projection still vary slightly after orientation and span corrections, especially in the rear three-quarter view; all four superseded attempts are retained.",
            "Visor/brim curvature, ear thickness and small highlights vary with generated view; compare sheet against approved idle.",
            "Rear construction is inferred because approved references have no rear view; plain rear shell is deliberately undecorated.",
            "At left profile the far stamp hand/handle is hidden and only part of the navy stamp base is visible.",
            "Generated backdrop is near-magenta with minor variation rather than exact flat #FF00FF; measured border key and despill were used.",
        ],
    }
    (ROOT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    for name, record in views.items():
        print(f"PASS {name}: {record['bytes']} bytes; RGBA {record['size']}; alpha bbox {record['alpha_bbox']}; no magenta spill/border/flame-corridor pixels")
    print("PASS one shared 0.53x scale; nozzle anchor (256, 494); five 512x512 WebP files <= 80,000 bytes")


if __name__ == "__main__":
    main()
